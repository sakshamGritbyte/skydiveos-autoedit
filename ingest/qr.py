_MANIFEST_SUFFIX = ".ingest.json"  # written by ingest.pull for every staged clip


@dataclass(frozen=True)
class _Marker:
    epoch: float
    filename: str
    staff_id: str


class QrSessionIndex:
    """Session map for one staging-day directory — a card-level view, not a walk.

    Attribution is deliberately **position-agnostic** for the common single-staff
    card: one staff id among the day's markers means every clip of that day is that
    staff's, whether the marker was filmed before the first jump, after the last, or
    halfway through. Only a card carrying *two or more* staff sessions needs to know
    which side of a marker its clips sit on, and that direction is inferred once from
    the card's layout (:meth:`_infer_direction`) rather than mandated as a filming
    protocol. A clip no marker can claim still gets ``staff_id=None``, and downstream
    falls back to the serial-based match exactly as before.
    """

    def __init__(self, epochs: dict[str, float], markers: list[_Marker]) -> None:
        self._epochs = epochs  # filename -> created_epoch
        self._markers = sorted(markers, key=lambda m: m.epoch)
        self._marker_files = {m.filename for m in self._markers}
        self._staff_markers = list(self._markers)
        staff_ids = {m.staff_id for m in self._staff_markers}
        #: Set when the whole day carries ONE staff: attribution ignores position.
        self._sole_staff = staff_ids.pop() if len(staff_ids) == 1 else None
        self._direction = LEADING if self._sole_staff else self._infer_direction()

    @classmethod
    def from_clips(
        cls, rows: Iterable[tuple[str, float, str | None]]
    ) -> QrSessionIndex:
        """Build an index from decoded ``(filename, epoch, staff_id)`` rows.

        For a caller that already has the decode results in hand — the card probe
        (``scripts/check_sdcard.py``) reads straight off the mount, where there are no
        ``.ingest.json`` manifests to walk — so a diagnostic reports the same
        attribution the pipeline will make, instead of re-implementing it.
        """
        epochs: dict[str, float] = {}
        markers: list[_Marker] = []
        for filename, epoch, staff_id in rows:
            epochs[filename] = float(epoch)
            if staff_id is not None:
                markers.append(
                    _Marker(epoch=float(epoch), filename=filename, staff_id=staff_id)
                )
        return cls(epochs, markers)

    @property
    def direction(self) -> str:
        """:data:`LEADING` / :data:`TRAILING` — which side of its clips a marker sits on."""
        return self._direction

    def _clip_epochs(self) -> list[float]:
        return [
            epoch for name, epoch in self._epochs.items() if name not in self._marker_files
        ]

    def _infer_direction(self) -> str:
        """Which side of its session each staff marker sits on, read off the layout.

        Only reached for a card with two or more staff sessions, where the side is the
        only thing separating them. Clips *before* the first marker with none after the
        last can only be markers that trail their sessions; clips after the last with
        none before the first can only be markers that lead. Anything else (clips on
        both outer edges, or on neither) reads equally well both ways — that is logged
        and falls back to :data:`LEADING`, the historical rule, rather than silently
        re-attributing footage a previously-working card already delivered.
        """
        if not self._staff_markers:
            return LEADING
        clips = self._clip_epochs()
        head = any(e < self._staff_markers[0].epoch for e in clips)
        tail = any(e > self._staff_markers[-1].epoch for e in clips)
        if head and not tail:
            logger.info(
                "card holds %d staff sessions and every clip precedes a marker: "
                "reading markers as END-of-session", len(self._staff_markers),
            )
            return TRAILING
        if not tail or head:
            logger.warning(
                "card holds %d staff sessions (%s) in a layout that reads both ways; "
                "attributing clips to the PRECEDING marker. Film one marker per "
                "session, consistently at the start or at the end of it.",
                len(self._staff_markers),
                ", ".join(sorted({m.staff_id or "?" for m in self._staff_markers})),
            )
        return LEADING

    def _staff_at(self, epoch: float) -> str | None:
        """The staff member governing a capture instant, or ``None`` if unclaimed."""
        if self._sole_staff is not None:
            return self._sole_staff
        if self._direction == TRAILING:
            return next(
                (m.staff_id for m in self._staff_markers if m.epoch >= epoch), None
            )
        staff: str | None = None
        for marker in self._staff_markers:
            if marker.epoch > epoch:
                break
            staff = marker.staff_id
        return staff

    def identity_for(self, mp4_path: str | Path) -> ClipIdentity:
        path = Path(mp4_path)
        if path.name in self._marker_files:
            marker = next(m for m in self._markers if m.filename == path.name)
            return ClipIdentity(staff_id=marker.staff_id, is_qr_marker=True)

        epoch = self._epochs.get(path.name)
        if epoch is None:
            try:
                epoch = path.stat().st_mtime
            except OSError:
                return ClipIdentity(staff_id=None)

        return ClipIdentity(staff_id=self._staff_at(epoch))


def build_session_index(
    day_dir: Path,
    *,
    max_clip_seconds: float = 60.0,
    scan_seconds: float = 8.0,
) -> QrSessionIndex:
    """Index one staging-day directory (``.../_camera-staging/<id>/<date>``).

    Capture order comes from each clip's ``.ingest.json`` manifest
    (``created_epoch``); QR decodes go through the sidecar cache, so rebuilding
    the index per lookup costs a directory read, not a video decode.
    """
    epochs: dict[str, float] = {}
    markers: list[_Marker] = []
    for manifest_path in sorted(day_dir.glob(f"*{_MANIFEST_SUFFIX}")):
        try:
            manifest = json.loads(manifest_path.read_text())
        except (ValueError, OSError) as e:
            logger.warning("unreadable ingest manifest %s: %r", manifest_path, e)
            continue
        mp4 = Path(str((manifest.get("files") or {}).get("mp4") or ""))
        if not mp4.name:
            continue
        epoch = manifest.get("created_epoch")
        if not isinstance(epoch, (int, float)):
            try:
                epoch = (day_dir / mp4.name).stat().st_mtime
            except OSError:
                continue
        epochs[mp4.name] = float(epoch)
        staff_id = cached_staff_qr(
            day_dir / mp4.name,
            max_clip_seconds=max_clip_seconds,
            scan_seconds=scan_seconds,
        )
        if staff_id is not None:
            markers.append(_Marker(epoch=float(epoch), filename=mp4.name, staff_id=staff_id))
    return QrSessionIndex(epochs, markers)


def qr_identity_resolver(
    matcher: Any | None = None,
    *,
    clock_tz: str | None = None,
    max_clip_seconds: float = 60.0,
    scan_seconds: float = 8.0,
) -> IdentityResolver:
    """The per-clip identity resolver discovery consumes in SD-card mode.

    Builds the session index from the clip's own staging directory (cheap — the
    sidecars are the cache), and, when a :class:`~ingest.match.FootageMatcher`
    is wired, fills the clip's load-derived role via ``resolve_for_staff``.
    Never raises and never blocks a hand-off: an unresolvable clip comes back
    with ``staff_id=None`` / ``role=None`` and the caller falls back exactly as
    it would without a resolver.
    """

    def _resolve(camera_id: str, mp4_path: str) -> ClipIdentity | None:
        try:
            index = build_session_index(
                Path(mp4_path).parent,
                max_clip_seconds=max_clip_seconds,
                scan_seconds=scan_seconds,
            )
            identity = index.identity_for(mp4_path)
        except Exception as e:  # noqa: BLE001 - attribution must never break the hand-off
            logger.exception("QR session attribution failed for %s: %r", mp4_path, e)
            return None

        if identity.is_qr_marker or identity.staff_id is None or matcher is None:
            return identity

        # Which jump (and therefore which role) is still per clip, from the load.
        from .discovery import _probe_capture_time  # noqa: PLC0415 - avoids a module cycle
        from .match import FootageMatchError

        captured_at = _probe_capture_time(mp4_path, clock_tz=clock_tz)
        if captured_at is None:
            return identity
        try:
            role = matcher.resolve_for_staff(identity.staff_id, captured_at).role
        except FootageMatchError as e:
            logger.warning(
                "load match for QR staff %s failed (%r); clip %s keeps no role",
                identity.staff_id, e, mp4_path,
            )
            return identity
        return ClipIdentity(staff_id=identity.staff_id, role=role)

    return _resolve
