def _probe_video(mp4_path: str | Path) -> tuple[float | None, int | None, int | None]:
    """Best-effort ``(duration_s, width, height)`` for a video file. Never raises."""
    try:
        out = subprocess.run(
            [
                "ffprobe", "-v", "error",
                "-select_streams", "v:0",
                "-show_entries", "stream=width,height:format=duration",
                "-of", "json", str(mp4_path),
            ],
            capture_output=True, text=True, timeout=_SUBPROCESS_TIMEOUT_S, check=False,
        )
        data = json.loads(out.stdout or "{}")
        streams = data.get("streams") or [{}]
        duration_raw = (data.get("format") or {}).get("duration")
        duration = float(duration_raw) if duration_raw is not None else None
        return duration, streams[0].get("width"), streams[0].get("height")
    except Exception as e:  # noqa: BLE001 - a bad file yields "unknown", not a crash
        logger.debug("ffprobe failed for %s: %r", mp4_path, e)
        return None, None, None


def _load_detectors() -> list[Any]:
    """QR detectors, best first. Raises an actionable error when OpenCV is absent."""
    try:
        import cv2
    except ImportError as e:  # pragma: no cover - environment-dependent
        raise RuntimeError(
            f"opencv-python is required for QR session markers but failed to import: {e!r}"
        ) from e

    detectors: list[Any] = []
    aruco = getattr(cv2, "QRCodeDetectorAruco", None)
    if aruco is not None:
        detectors.append(aruco())
    detectors.append(cv2.QRCodeDetector())
    return detectors


#: Barrel-distortion coefficients tried per frame when the flat decode fails.
#: A GoPro's wide FOV bows the code enough that OpenCV *locates* it but mis-samples
#: the modules (verified on real handcam footage: flat decode failed on every frame,
#: k1=-0.25 read it cleanly). Zero must stay first — the fast path for a flat,
#: printed code or a camera in Linear lens mode.
_UNDISTORT_K1_SWEEP: tuple[float, ...] = (0.0, -0.18, -0.25, -0.32)


def _decode_qr_frame(gray: Any, detectors: list[Any]) -> str | None:
    """Decode one grayscale frame, sweeping fisheye undistortion. Never raises."""
    import cv2
    import numpy as np

    h, w = gray.shape[:2]
    camera = np.array([[w * 0.7, 0, w / 2], [0, w * 0.7, h / 2], [0, 0, 1]], np.float64)
    for k1 in _UNDISTORT_K1_SWEEP:
        candidate = gray if k1 == 0.0 else cv2.undistort(
            gray, camera, np.array([k1, 0.0, 0.0, 0.0], np.float64)
        )
        if max(h, w) > 2000:  # decoders sample better below ~2k on big frames
            candidate = cv2.resize(candidate, None, fx=0.5, fy=0.5, interpolation=cv2.INTER_AREA)
        for detector in detectors:
            try:
                payload, _points, _straight = detector.detectAndDecode(candidate)
            except Exception:  # noqa: BLE001 - a detector crash on one frame is not fatal
                continue
            staff_id = parse_staff_payload(payload)
            if staff_id is not None:
                return staff_id
    return None


def decode_staff_qr(
    mp4_path: str | Path,
    *,
    scan_seconds: float = 8.0,
    fps: float = 2.0,
) -> str | None:
    """Decode a staff QR from the head of a clip, or ``None``.

    Samples ``fps`` frames/second from the first ``scan_seconds`` at the clip's
    native resolution (downscaling first destroys the code — this is why
    ``analysis.extract`` isn't reused: it targets proxies and shrinks frames).
    Frames stream through one at a time (a 4K rgb24 frame is ~24 MB; never
    buffer the lot); each is tried flat and through the fisheye undistortion
    sweep (:data:`_UNDISTORT_K1_SWEEP` — a GoPro's wide lens bows the code past
    what a flat decode tolerates). First payload carrying
    :data:`QR_STAFF_PREFIX` wins. Never raises for a bad file — that's just
    "no QR here".
    """
    import cv2
    import numpy as np

    detectors = _load_detectors()
    _, width, height = _probe_video(mp4_path)
    if not width or not height:
        return None
    frame_bytes = width * height * 3

    proc = subprocess.Popen(
        [
            "ffmpeg", "-v", "error",
            "-t", f"{scan_seconds:.3f}",
            "-i", str(mp4_path),
            "-vf", f"fps={fps:g}",
            "-pix_fmt", "rgb24", "-f", "rawvideo", "pipe:1",
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
    )
    try:
        assert proc.stdout is not None
        while True:
            chunk = proc.stdout.read(frame_bytes)
            if len(chunk) < frame_bytes:
                return None
            frame = np.frombuffer(chunk, dtype=np.uint8).reshape(height, width, 3)
            gray = cv2.cvtColor(frame, cv2.COLOR_RGB2GRAY)
            staff_id = _decode_qr_frame(gray, detectors)
            if staff_id is not None:
                logger.info("QR session marker in %s -> staff %s", mp4_path, staff_id)
                return staff_id
    finally:
        proc.kill()
        proc.wait(timeout=_SUBPROCESS_TIMEOUT_S)


def _sidecar_path(mp4_path: Path) -> Path:
    return mp4_path.with_suffix(QR_SIDECAR_SUFFIX)


def cached_staff_qr(
    mp4_path: Path,
    *,
    max_clip_seconds: float = 60.0,
    scan_seconds: float = 8.0,
) -> str | None:
    """:func:`decode_staff_qr` with a duration gate and a sidecar cache.

    Only clips shorter than ``max_clip_seconds`` are probed — a deliberate
    marker clip is seconds long, and this keeps 20-minute jumps out of the
    decoder. Both outcomes are cached in ``<stem>.qr.json`` so a clip is
    decoded at most once ever, no matter how many scans revisit the folder.
    """
    sidecar = _sidecar_path(mp4_path)
    if sidecar.exists():
        try:
            cached = json.loads(sidecar.read_text())
            staff_id = cached.get("staff_id")
            return staff_id if isinstance(staff_id, str) else None
        except (ValueError, OSError):
            logger.warning("unreadable QR sidecar %s; re-decoding", sidecar)

    duration, _w, _h = _probe_video(mp4_path)
    result: dict[str, Any] = {"staff_id": None, "skipped": None, "decoded_at": time.time()}
    if duration is not None and duration > max_clip_seconds:
        result["skipped"] = "too-long"
    else:
        result["staff_id"] = decode_staff_qr(mp4_path, scan_seconds=scan_seconds)

    try:
        sidecar.write_text(json.dumps(result, indent=2) + "\n")
    except OSError as e:
        logger.warning("could not write QR sidecar %s: %r", sidecar, e)
    staff_id = result["staff_id"]
    return staff_id if isinstance(staff_id, str) else None


